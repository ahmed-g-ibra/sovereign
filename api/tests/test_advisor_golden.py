"""Golden fixture shared with the JavaScript advisor.

The site is static, so the advisor also exists as a browser implementation in
web/src/lib/advisor.js. Two implementations of the same rules is the hazard
ADR 0006 already identified for request signing, and it is handled the same
way: one fixture, asserted on both sides, so drift fails a test instead of
quietly giving two different answers to the same question.

Regenerate after an intentional change to the rules, the knowledge base or
the advisor:

    UPDATE_GOLDEN=1 uv run pytest tests/test_advisor_golden.py
"""

from __future__ import annotations

import json
import os
import pathlib

from sovereign_api import advisor, knowledge

FIXTURE = (pathlib.Path(__file__).resolve().parents[2]
           / "knowledge" / "fixtures" / "advisor-golden.json")

# Fixed inputs, so the fixture does not move when the probe reports.
CANDIDATES = [
    {"id": "aws-me-central-1", "provider": "aws", "region": "me-central-1",
     "country": "AE", "city": "Dubai"},
    {"id": "aws-me-south-1", "provider": "aws", "region": "me-south-1",
     "country": "BH", "city": "Manama"},
    {"id": "gcp-me-central1", "provider": "gcp", "region": "me-central1",
     "country": "QA", "city": "Doha"},
    {"id": "gcp-me-central2", "provider": "gcp", "region": "me-central2",
     "country": "SA", "city": "Dammam"},
    {"id": "oci-me-dubai-1", "provider": "oci", "region": "me-dubai-1",
     "country": "AE", "city": "Dubai"},
]

LATENCY = {
    "aws-me-central-1": {"samples": 40, "loss_pct": 0.0, "p50_ms": 132.6, "p95_ms": 141.0},
    "gcp-me-central1": {"samples": 40, "loss_pct": 0.0, "p50_ms": 62.3, "p95_ms": 294.1},
    "gcp-me-central2": {"samples": 40, "loss_pct": 0.0, "p50_ms": 69.8, "p95_ms": 304.0},
    "oci-me-dubai-1": {"samples": 40, "loss_pct": 0.0, "p50_ms": 451.2, "p95_ms": 627.9},
    # Reachable but totally lossy: samples, no percentile. The case that once
    # crashed the ranking.
    "aws-me-south-1": {"samples": 40, "loss_pct": 100.0, "p50_ms": None, "p95_ms": None},
}

WINDOW = "7 days"
PROBE_COUNTRIES = ["OM"]

CASES = [
    {"name": "omani workload, personal data",
     "user_countries": ["OM"], "data_classes": ["personal"]},
    {"name": "uae health data triggers localisation",
     "user_countries": ["AE"], "data_classes": ["health"]},
    {"name": "unknown jurisdiction stays unknown",
     "user_countries": ["KW"], "data_classes": ["personal"]},
    {"name": "multiple jurisdictions take the worst verdict",
     "user_countries": ["OM", "SA", "BH"], "data_classes": ["personal", "sensitive"]},
    {"name": "country with no entry is skipped",
     "user_countries": ["ZZ", "OM"], "data_classes": ["personal"]},
]


def _record(case, entries, rules) -> dict:
    out = advisor.advise(
        user_countries=case["user_countries"],
        data_classes=case["data_classes"],
        entries=entries,
        rules=rules,
        candidate_regions=[dict(c) for c in CANDIDATES],
        latency=LATENCY,
        window=WINDOW,
        probe_countries=PROBE_COUNTRIES,
    )
    out.pop("generated_at")  # the one field that is not deterministic
    return out


def _build() -> dict:
    entries = knowledge.load_entries()
    rules = knowledge.load_rules()
    return {
        "note": ("Generated by api/tests/test_advisor_golden.py. Asserted by "
                 "that test and by web/test/advisor.golden.test.js, so the "
                 "Python and JavaScript advisors cannot drift apart."),
        "entries": {code: e.public() for code, e in sorted(entries.items())},
        "rules": {"version": rules.version, "obligations": rules.obligations,
                  "rules": rules.rules},
        "candidate_regions": CANDIDATES,
        "latency": LATENCY,
        "window": WINDOW,
        "probe_countries": PROBE_COUNTRIES,
        "cases": [{**case, "expected": _record(case, entries, rules)}
                  for case in CASES],
    }


def test_golden_fixture_matches():
    built = _build()

    if os.environ.get("UPDATE_GOLDEN") == "1":
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(json.dumps(built, indent=2, default=str) + "\n")
        return

    assert FIXTURE.exists(), (
        "fixture missing; regenerate with UPDATE_GOLDEN=1")
    stored = json.loads(FIXTURE.read_text())

    # Compared piece by piece so a failure says which half moved: the inputs
    # (knowledge base or rules edited) or the outputs (advisor logic changed).
    assert stored["entries"] == built["entries"], (
        "the knowledge base changed; regenerate with UPDATE_GOLDEN=1")
    assert stored["rules"] == built["rules"], (
        "the rules changed; regenerate with UPDATE_GOLDEN=1")

    for stored_case, built_case in zip(stored["cases"], built["cases"]):
        assert stored_case["name"] == built_case["name"]
        assert stored_case["expected"] == built_case["expected"], (
            f"advisor output changed for {stored_case['name']!r}; if intended, "
            f"regenerate with UPDATE_GOLDEN=1 and check the JS advisor still agrees")
